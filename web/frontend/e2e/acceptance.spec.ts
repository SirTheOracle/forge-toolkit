import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { FIXTURE, dispatchCalls, resetEmptyFixture } from "./helpers";
test.beforeEach(resetEmptyFixture);
function alter(change: Record<string, unknown>) {
  const path=resolve(FIXTURE,"fixture-state.json");
  writeFileSync(path, JSON.stringify({...JSON.parse(readFileSync(path,"utf8")),...change}));
}
test("empty fleet through spawn, answer, park/resolve, scoped ack, failures and recreation", async ({ page }) => {
  test.setTimeout(100_000);
  await page.goto("/");
  await expect(page.getByText("No live Forge sessions.")).toBeVisible();
  await expect(page.getByLabel("Spawn root")).toContainText("fixture");
  await page.getByLabel("Spawn name").fill("forge-e2e");
  await page.getByRole("button",{name:"Spawn",exact:true}).click();
  await expect(page.getByRole("button",{name:/^forge-e2e.*alpha/})).toBeVisible({timeout:15_000});
  await expect(page.getByRole("heading",{name:"Stage facts"})).toBeVisible();
  await page.getByLabel("Spawn name").fill("forge-beta");
  await page.getByRole("button",{name:"Spawn",exact:true}).click();
  await expect(page.getByText("Already active at that root — no-op (ensure semantics).")).toBeVisible();
  const stateBefore=JSON.parse(readFileSync(resolve(FIXTURE,"fixture-state.json"),"utf8"));
  expect(stateBefore.sessions).toHaveLength(1);
  execFileSync(resolve(FIXTURE,"venv/bin/python3"), [resolve(FIXTURE,"bin/cli.py"), "seed-session", "--root", stateBefore.sessions[0].root, "--name", "forge-beta"]);
  await expect(page.getByRole("button",{name:/^forge-beta.*beta/})).toBeVisible({timeout:15_000});
  await page.getByRole("button",{name:/^forge-e2e.*alpha/}).click();
  await expect(page.getByText("Build the alpha capability for operators.").last()).toBeVisible();
  await expect(page.getByText("beta needs input")).toHaveCount(0);
  await page.getByLabel("answer ask-alpha").fill("take path A");
  await page.getByRole("button",{name:"Answer",exact:true}).click();
  await expect(page.getByText(/Delivered to pane 0/)).toBeVisible();
  await expect(page.getByText("reply: take path A",{exact:true})).toBeVisible({timeout:15_000});
  await page.getByLabel("note alpha/coding").fill("wait for operator");
  await page.getByRole("button",{name:"Park",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Resolve parked · alpha/coding"})).toBeVisible({timeout:15_000});
  await page.getByRole("button",{name:"Resolve",exact:true}).click();
  await expect(page.getByText("Resolved.",{exact:true})).toBeVisible();
  await page.getByLabel("Ack scope").selectOption("root_basename");
  await expect(page.getByRole("button",{name:"Acknowledge fixture",exact:true})).toBeVisible();
  await expect(page.getByText(/Plus 1 matching condition/)).toBeVisible();
  await page.getByRole("button",{name:"Acknowledge fixture",exact:true}).click();
  await expect(page.getByText(/acked: NEEDS-ASK/)).toBeVisible();
  await page.getByRole("button",{name:"Pause",exact:true}).click();
  await expect(page.getByText(/Pause REQUESTED/)).toBeVisible();
  await page.getByLabel("message").fill("forge-resume");
  const before=dispatchCalls().length;
  let lost=false;
  await page.route("**/actions/message", async route=> {
    if (!lost) { lost=true; await route.fetch(); await route.abort(); }
    else await route.continue();
  });
  await page.getByRole("button",{name:"Send",exact:true}).click();
  await expect(page.getByRole("button",{name:"Reconcile same request"})).toBeVisible();
  await page.getByRole("button",{name:/^forge-beta.*beta/}).click();
  await expect(page.getByText(/Response lost/)).toHaveCount(0);
  await page.getByRole("button",{name:/^forge-e2e.*alpha/}).click();
  await page.getByRole("button",{name:"Reconcile same request"}).click();
  await expect(page.getByText(/Delivered to pane 0/)).toBeVisible();
  expect(dispatchCalls().length).toBe(before+1);
  alter({tmux_fail:true,board_busy:true});
  await expect(page.getByText(/tmux unavailable; retained fleet is stale/)).toBeVisible({timeout:15_000});
  await expect(page.getByRole("button",{name:/^forge-e2e.*alpha/})).toBeVisible();
  await expect(page.getByText(/Board: busy/)).toBeVisible({timeout:20_000});
  alter({tmux_fail:false,board_busy:false});
  const state=JSON.parse(readFileSync(resolve(FIXTURE,"fixture-state.json"),"utf8"));
  state.sessions[0].id="$99";state.sessions[0].created=2000000000;alter({sessions:state.sessions});
  await expect(page.getByRole("button",{name:/^forge-e2e.*\$99/})).toBeVisible({timeout:15_000});
  await page.getByRole("button",{name:/^forge-e2e.*\$99/}).click();
  await expect(page.getByText("reply: take path A",{exact:true})).toHaveCount(0);
  await expect(page.getByText("reply: forge-resume",{exact:true})).toHaveCount(0);
});