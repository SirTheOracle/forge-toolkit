#!/usr/bin/env node
import { execFileSync, spawn } from "node:child_process";
import { chmodSync, cpSync, mkdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const frontend=resolve(dirname(fileURLToPath(import.meta.url)), "..");
const original=resolve(frontend,"../..");
const base=resolve(frontend,".e2e-checkout");
const port=process.env.FORGE_WEB_E2E_PORT ?? "8799";
rmSync(base,{recursive:true,force:true});
for(const dir of ["bin","tools","web/backend","web/frontend","fixture/.dev/attention/payloads","fixture/.dev/attention/archive","fixture/.dev/forge-tmp/callbacks","home/.config/forge"]) mkdirSync(resolve(base,dir),{recursive:true});
cpSync(resolve(original,"bin/forge-web"),resolve(base,"bin/forge-web"));chmodSync(resolve(base,"bin/forge-web"),0o755);
cpSync(resolve(original,"web/backend/src"),resolve(base,"web/backend/src"),{recursive:true});
cpSync(resolve(original,"web/backend/pyproject.toml"),resolve(base,"web/backend/pyproject.toml"));
cpSync(resolve(frontend,"dist"),resolve(base,"web/frontend/dist"),{recursive:true});
cpSync(resolve(frontend,"fixtures/cli.py"),resolve(base,"bin/cli.py"));chmodSync(resolve(base,"bin/cli.py"),0o755);
for(const name of ["forge","forge-bridge","forge-watch","forge-start","forge-broker"]) symlinkSync("cli.py",resolve(base,"bin",name));
cpSync(resolve(base,"bin/cli.py"),resolve(base,"tools/tmux")); chmodSync(resolve(base,"tools/tmux"),0o755);
const root=resolve(base,"fixture");
writeFileSync(resolve(base,"fixture-state.json"),JSON.stringify({sessions:[]}));writeFileSync(resolve(base,"stub.log"),"");
writeFileSync(resolve(base,"home/.config/forge/registry.yml"),`repos:\n  fixture:\n    alias: fixture\n    path: ${root}\n`);
const python=process.env.FORGE_WEB_E2E_PYTHON ?? "python3";
execFileSync(python,["-m","venv",resolve(base,"venv")],{stdio:"inherit"});
execFileSync(resolve(base,"venv/bin/python3"),["-m","pip","install","--quiet","--cache-dir",resolve(base,"pip-cache"),"-e",resolve(base,"web/backend")],{stdio:"inherit"});
const env={...process.env,HOME:resolve(base,"home"),PATH:`${resolve(base,"venv/bin")}:${resolve(base,"tools")}:${process.env.PATH ?? ""}`, FORGE_WEB_ALLOW_TEST_OVERRIDES:"1",FORGE_WATCH_TRIGGER:"0"};
delete env.TMUX; delete env.TMUX_PANE;
execFileSync(resolve(base,"bin/forge-web"),["--check","--port",port],{env,stdio:"inherit"});
const server=spawn(resolve(base,"bin/forge-web"),["--port",port],{env,stdio:"inherit"});
for(const event of ["SIGINT","SIGTERM"]) process.on(event,()=>server.kill("SIGTERM"));
server.on("exit",code=>process.exit(code ?? 0));